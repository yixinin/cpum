/**
 * 翻译 key, 支持 {param} 插值。
 * 模块级导出 —— 组件外 (composable / 普通 ts) 也可直接调用;
 * 在组件模板/computed 中调用时会自动追踪 locale 变化并触发更新。
 */
export function t(key: string, params?: Record<string, string | number>): string {
  let text = messages[locale.value][key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function useI18n() {
  const toggleLocale = () => {
    locale.value = locale.value === "zh-CN" ? "en-US" : "zh-CN";
    localStorage.setItem("cpum-locale", locale.value);
  };
  return { locale: computed(() => locale.value), t, toggleLocale };
}
